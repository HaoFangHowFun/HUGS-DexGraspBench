"""Build bench-local MJCF controllers from the independent Sharpa URDF assets."""
import copy
import hashlib
import json
import os
from pathlib import Path
import xml.etree.ElementTree as ET

import mujoco
import yaml

REPO = Path(__file__).resolve().parents[1]


def main():
    config = yaml.safe_load((REPO / "config/sharpa_validation.yaml").read_text())
    assets = (REPO / config["asset_root"]).resolve()
    provenance = json.loads((assets / "provenance.json").read_text())
    for side in ("right", "left"):
        urdf = assets / "urdf" / f"{side}_sharpa_wave_with_flange.urdf"
        spec = mujoco.MjSpec.from_file(str(urdf))
        compiled = spec.compile()
        root = ET.fromstring(spec.to_xml())
        # MuJoCo's XML writer rounds floats. Retain full kinematic precision.
        vector = lambda values: " ".join(format(float(value), ".17g") for value in values)
        for body in root.findall(".//body"):
            original = compiled.body(body.get("name"))
            body.set("pos", vector(original.pos))
            body.set("quat", vector(original.quat))
        for joint in root.findall(".//joint"):
            original = compiled.joint(joint.get("name"))
            joint.set("pos", vector(original.pos))
            joint.set("axis", vector(original.axis))
            joint.set("range", vector(original.range))
            joint.set("solreflimit", vector(config["joint_limit_solref"]))
            joint.set("solimplimit", vector(config["joint_limit_solimp"]))
            joint.set("armature", str(config["joint_armature"]))
        output = REPO / "assets/hand/sharpa_wave" / f"{side}.xml"
        output.parent.mkdir(parents=True, exist_ok=True)
        root.insert(0, ET.Comment(
            f"Generated by scripts/build_sharpa_models.py; source {provenance['source_commit']}; "
            f"MuJoCo {mujoco.__version__}. Simulation gains are provisional."))
        root.find("compiler").set("meshdir", os.path.relpath(assets / "meshes" / side, output.parent))
        manifest = json.loads((REPO / config["palm_decomposition"]["directory"] / "manifest.json").read_text())
        record = manifest["hands"][side]
        source = assets / record["source"]
        if hashlib.sha256(source.read_bytes()).hexdigest() != record["source_sha256"]:
            raise ValueError("Palm source changed; rebuild collision parts")
        palm = root.find(f".//body[@name='{side}_hand_C_MC']")
        original_geom = palm.find(f"geom[@mesh='{side}_hand_C_MC']")
        palm.remove(original_geom)
        for index, part in enumerate(record["parts"]):
            path = REPO / part["path"]
            if hashlib.sha256(path.read_bytes()).hexdigest() != part["sha256"]:
                raise ValueError(f"Collision part checksum mismatch: {path}")
            name = f"{side}_palm_collision_{index:02d}"
            ET.SubElement(root.find("asset"), "mesh", name=name,
                          file=os.path.relpath(path, assets / "meshes" / side))
            geom = copy.deepcopy(original_geom)
            geom.set("name", name)
            geom.set("mesh", name)
            palm.append(geom)
        if config["self_collision_exclusions"]:
            contact = ET.SubElement(root, "contact")
            for first, second in config["self_collision_exclusions"]:
                ET.SubElement(contact, "exclude", body1=f"{side}_{first}", body2=f"{side}_{second}")
        ET.SubElement(root, "option", timestep=str(config["timestep"]), integrator="implicitfast", gravity="0 0 0")
        actuator = ET.SubElement(root, "actuator")
        for joint in ET.parse(urdf).findall("joint"):
            if joint.get("type") == "fixed":
                continue
            limit = joint.find("limit")
            effort = float(limit.get("effort"))
            ET.SubElement(actuator, "position", name=f"{joint.get('name')}_position", joint=joint.get("name"),
                          kp=str(config["position_kp"]), kv=str(config["position_kv"]),
                          ctrllimited="true", ctrlrange=f"{limit.get('lower')} {limit.get('upper')}",
                          forcelimited="true", forcerange=f"{-effort} {effort}")
        ET.indent(root)
        ET.ElementTree(root).write(output, encoding="utf-8", xml_declaration=True)
        model = mujoco.MjModel.from_xml_path(str(output))
        if model.nq != 22 or model.nu != 22:
            raise RuntimeError(f"Invalid model dimensions for {side}")
        print(f"Built {output.relative_to(REPO)}: nq={model.nq}, nu={model.nu}")


if __name__ == "__main__":
    main()
